"""Exercise real HTTP -> PostgreSQL outbox -> Redis/Celery -> authorized API -> web."""
import hashlib
import hmac
import json
import os
import time
from datetime import datetime, timezone
from uuid import uuid4

import httpx
from sqlalchemy import func, select

from app.core.config import get_settings
from app.domain.models import Delivery, Issue, Outbox
from app.infra.database import get_session_factory


def main():
    config = get_settings()
    if config.app_env != "development" or not config.demo_auth_enabled:
        raise RuntimeError("Smoke requires enabled local development demo")
    identifier = int(time.time_ns() // 1000)
    delivery = str(uuid4())
    title = f"[Demo] Signed ingestion smoke {identifier}"
    raw = json.dumps({"action": "opened", "installation": {"id": 1001},
                      "repository": {"id": 2001, "private": False},
                      "issue": {"id": identifier, "number": identifier % 1_999_999_999 + 1, "title": title,
                                "body": "Generated by make smoke; demo data.", "state": "open",
                                "updated_at": datetime.now(timezone.utc).isoformat()}}).encode()
    headers = {"Content-Type": "application/json", "X-GitHub-Event": "issues",
               "X-GitHub-Delivery": delivery,
               "X-Hub-Signature-256": "sha256=" + hmac.new(
                   config.github_webhook_secret.get_secret_value().encode(), raw,
                   hashlib.sha256).hexdigest()}
    auth = {"Authorization": "Bearer " + config.demo_api_token.get_secret_value()}
    with httpx.Client(base_url=os.getenv("SMOKE_API_URL", "http://api:8000"), timeout=10) as client:
        assert client.get("/ready").status_code == 200, "Readiness failed"
        assert client.get("/v1/repositories").status_code == 401, "Missing token accepted"
        assert client.get("/v1/repositories/2001/issues").status_code == 401, (
            "Unauthenticated issue access accepted"
        )
        assert client.get("/v1/repositories", headers={"Authorization": "Bearer invalid"}).status_code == 401, (
            "Invalid token accepted"
        )
        assert client.post("/v1/webhooks/github", content=raw,
                           headers={**headers, "X-Hub-Signature-256": "sha256=bad"}).status_code == 401
        assert client.post("/v1/webhooks/github", content=raw, headers=headers).status_code == 202
        assert client.post("/v1/webhooks/github", content=raw, headers=headers).status_code == 200
        for _ in range(60):
            response = client.get("/v1/repositories/2001/issues", headers=auth)
            response.raise_for_status()
            matches = [i for i in response.json()["items"] if i["title"] == title]
            if matches:
                assert len(matches) == 1
                break
            time.sleep(1)
        else:
            raise AssertionError("Worker did not persist the signed issue within 60 seconds")
    with get_session_factory()() as db:
        assert db.get(Delivery, delivery)
        assert db.get(Outbox, delivery).status == "processed"
        assert db.scalar(select(Issue).where(Issue.id == identifier)).title == title
        assert db.scalar(select(func.count()).select_from(Issue).where(
            Issue.repository_id == 2001, Issue.number == identifier % 1_999_999_999 + 1
        )) == 1, "Issue was duplicated"
    web = os.getenv("SMOKE_WEB_URL", "http://web:3000")
    with httpx.Client(timeout=10) as browser:
        assert browser.get(web).status_code == 200
        response = browser.get(web + "/api/dashboard?repository=2001")
        response.raise_for_status()
        assert any(i["title"] == title for i in response.json()["items"])
    print("PASS: auth rejection, signature rejection, durable delivery, deduplication, real worker, DB, API, web data")


if __name__ == "__main__":
    main()
